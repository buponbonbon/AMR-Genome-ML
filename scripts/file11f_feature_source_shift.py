#!/usr/bin/env python3
"""
FILE11F — FEATURE-GENERATION SOURCE-SHIFT / DEBIASING SENSITIVITY
=================================================================

Purpose
-------
Fast go/no-go diagnostic for a potential feature-generation source artifact in
the known-AMR representation.

Development known-AMR rows were generated through two branches:
  1) NCBI Pathogen Detection precomputed AMR genotypes
  2) local AMRFinderPlus completion for 382 unresolved genomes

External E2 was called locally with AMRFinderPlus. FILE11F asks:
  - Can the 668-feature vector predict which development branch generated it?
  - Which features carry the strongest source association?
  - Do source-associated features overlap high-impact resistance-model features?
  - Does a DEVELOPMENT-ONLY source-debiased model change external E2 behavior?
  - Does training only on the source-matched local branch change E2 behavior?

IMPORTANT
---------
This is a POST-HOC EXPLORATORY SENSITIVITY ANALYSIS designed after FILE11C E2
results were known. It MUST NOT replace the frozen FILE11C primary external
result and MUST NOT be described as confirmatory.

No E2 labels are used to:
  - define source markers,
  - select features,
  - tune C,
  - tune threshold,
  - select a model.

All pre-specified sensitivity models are reported. No "best model" is selected.

Primary fixed source-marker rule
--------------------------------
A feature is a source marker iff, in the 4,227 development genomes:
  - Benjamini-Hochberg q <= 0.01 for NCBI-vs-local Fisher exact test, AND
  - absolute prevalence difference >= 0.20.

The source-debiased model removes ALL features meeting that rule, then fits the
same locked LogisticRegression specification as FILE11C:
  C=1.0, solver=liblinear, class_weight=None, max_iter=3000,
  random_state=20260920, threshold=0.5.

Pre-specified sensitivity models
--------------------------------
  frozen_original
      FILE11C predictions; never refit.

  source_debiased_full
      All 4,227 development genomes; source-marker features removed.

  local_source_only
      Development genomes generated by local AMRFinder branch only;
      all 668 frozen features retained.

  ncbi_source_only
      Development genomes generated by NCBI-precomputed branch only;
      all 668 frozen features retained.

Caveat
------
The source branch is NOT randomized. Source associations may reflect technical
differences, population/lineage differences, calendar/accession differences, or
a mixture. FILE11F diagnoses source separability; it cannot by itself prove
causality.

Typical run
-----------
python scripts/file11f_feature_source_shift.py \
  --project-root /mnt/c/Users/ASUS/Desktop/AMR-Genome-ML \
  --bootstrap-replicates 2000

Optional if automatic development-label discovery fails:
  --development-labels /path/to/file07_or_phenotype_table.csv

Outputs
-------
data/external_validation/ncbi_pathogen_detection/file11f/
  file11f_source_feature_associations.csv
  file11f_source_classifier_cv.csv
  file11f_source_outcome_confounding.csv
  file11f_source_marker_overlap.csv
  file11f_internal_cv_sensitivity.csv
  file11f_external_sensitivity_metrics.csv
  file11f_external_paired_cluster_bootstrap.csv
  file11f_external_sensitivity_predictions.csv
  file11f_analysis_design.json
  file11f_label_source_audit.csv

checkpoints/external_validation_file11f/
  file11f_final_summary.json
  file11f_last_failure.json
"""

