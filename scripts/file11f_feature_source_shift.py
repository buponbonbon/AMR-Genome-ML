BOOT_METRICS = (
    "roc_auc",
    "average_precision",
    "balanced_accuracy",
    "mcc",
    "sensitivity",
    "specificity",
    "brier",
    "log_loss",
)


def paired_cluster_bootstrap(
    pred_df: pd.DataFrame,
    method_scores: dict[str, np.ndarray],
    n_boot: int,
    seed: int,
) -> pd.DataFrame:
    y_all = pred_df["label_binary"].to_numpy(dtype=np.uint8)
    erd = pred_df["erd_group"].astype(str).to_numpy()
    unique_groups = np.unique(erd)
    group_idx = {g: np.flatnonzero(erd == g) for g in unique_groups}
    rng = np.random.default_rng(seed)

    comparators = [m for m in method_scores if m != "frozen_original"]
    draws = {
        comp: {metric: [] for metric in BOOT_METRICS}
        for comp in comparators
    }

    point = {}
    for name, p in method_scores.items():
        pr = (np.asarray(p) >= THRESHOLD).astype(np.uint8)
        point[name] = metric_bundle(y_all, p, pr)

    valid = 0
    for b in range(n_boot):
        if STOP:
            raise KeyboardInterrupt

        sampled = rng.choice(unique_groups, size=len(unique_groups), replace=True)
        idx = np.concatenate([group_idx[g] for g in sampled])
        y = y_all[idx]
        if len(np.unique(y)) < 2:
            continue

        base_p = np.asarray(method_scores["frozen_original"])[idx]
        base = metric_bundle(y, base_p, (base_p >= THRESHOLD).astype(np.uint8))

        for comp in comparators:
            cp = np.asarray(method_scores[comp])[idx]
            cm = metric_bundle(y, cp, (cp >= THRESHOLD).astype(np.uint8))
            for metric in BOOT_METRICS:
                if np.isfinite(cm[metric]) and np.isfinite(base[metric]):
                    # comparator minus frozen original
                    draws[comp][metric].append(cm[metric] - base[metric])

        valid += 1
        if b == 0 or (b + 1) % 250 == 0 or b + 1 == n_boot:
            log(f"[PROGRESS] paired ERD bootstrap {b+1}/{n_boot} | valid={valid}")

    rows = []
    for comp in comparators:
        for metric in BOOT_METRICS:
            arr = np.asarray(draws[comp][metric], dtype=float)
            if len(arr) == 0:
                continue
            rows.append(
                {
                    "contrast": f"{comp}_minus_frozen_original",
                    "model": comp,
                    "metric": metric,
                    "point_frozen_original": point["frozen_original"][metric],
                    "point_sensitivity_model": point[comp][metric],
                    "point_delta": point[comp][metric] - point["frozen_original"][metric],
                    "delta_definition": (
                        "sensitivity model minus frozen original; positive favors "
                        "sensitivity model for AUROC/AP/BA/MCC/sensitivity/specificity; "
                        "negative favors sensitivity model for Brier/log_loss"
                    ),
                    "n_boot_requested": n_boot,
                    "n_boot_valid": len(arr),
                    "bootstrap_delta_mean": float(arr.mean()),
                    "ci95_low": float(np.quantile(arr, 0.025)),
                    "ci95_high": float(np.quantile(arr, 0.975)),
                }
            )

    return pd.DataFrame(rows)


