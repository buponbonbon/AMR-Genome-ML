def internal_cv_model(
    X: pd.DataFrame,
    y: np.ndarray,
    feature_names: list[str],
    subset_mask: np.ndarray,
    model_name: str,
) -> dict[str, Any]:
    idx = np.flatnonzero(subset_mask)
    yy = np.asarray(y, dtype=np.uint8)[idx]
    XX = X.loc[idx, feature_names].to_numpy(dtype=np.float64)

    if len(idx) < 50 or len(np.unique(yy)) < 2:
        return {
            "model": model_name,
            "n": len(idx),
            "R": int(yy.sum()),
            "S": int(len(yy) - yy.sum()),
            "cv_scheme": "stratified_random_5fold",
            "roc_auc": np.nan,
            "average_precision": np.nan,
            "balanced_accuracy": np.nan,
            "mcc": np.nan,
            "note": "Insufficient rows/classes for 5-fold sensitivity CV",
        }

    n_splits = 5
    min_class = min(int(yy.sum()), int((1 - yy).sum()))
    if min_class < 5:
        n_splits = max(2, min_class)

    skf = StratifiedKFold(
        n_splits=n_splits,
        shuffle=True,
        random_state=RANDOM_SEED,
    )
    oof = np.full(len(yy), np.nan, dtype=float)

    for tr, te in skf.split(XX, yy):
        m = new_outcome_model()
        m.fit(XX[tr], yy[tr])
        oof[te] = positive_probability(m, XX[te])

    pred = (oof >= THRESHOLD).astype(np.uint8)
    met = metric_bundle(yy, oof, pred)
    return {
        "model": model_name,
        "n": met["n"],
        "R": met["R"],
        "S": met["S"],
        "cv_scheme": f"stratified_random_{n_splits}fold",
        "roc_auc": met["roc_auc"],
        "average_precision": met["average_precision"],
        "balanced_accuracy": met["balanced_accuracy"],
        "mcc": met["mcc"],
        "sensitivity": met["sensitivity"],
        "specificity": met["specificity"],
        "brier": met["brier"],
        "log_loss": met["log_loss"],
    }


