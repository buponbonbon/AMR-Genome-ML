def source_classifier_cv(
    X: pd.DataFrame,
    source_local: np.ndarray,
    feature_names: list[str],
    mlst: pd.Series | None,
) -> pd.DataFrame:
    Xn = X[feature_names].to_numpy(dtype=np.float64)
    y = np.asarray(source_local, dtype=np.uint8)

    rows = []

    def run_scheme(name: str, splits):
        oof = np.full(len(y), np.nan, dtype=float)
        fold_ids = np.full(len(y), -1, dtype=int)

        for fold, (tr, te) in enumerate(splits, start=1):
            if STOP:
                raise KeyboardInterrupt
            if len(np.unique(y[tr])) < 2 or len(np.unique(y[te])) < 2:
                raise RuntimeError(
                    f"{name} source-CV fold {fold} lacks both source classes."
                )
            model = new_source_model()
            model.fit(Xn[tr], y[tr])
            oof[te] = positive_probability(model, Xn[te])
            fold_ids[te] = fold

        if np.isnan(oof).any() or (fold_ids < 0).any():
            raise RuntimeError(f"Incomplete OOF source predictions for {name}.")

        pred = (oof >= 0.5).astype(np.uint8)
        tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()

        rows.append(
            {
                "scheme": name,
                "n": len(y),
                "local_n": int(y.sum()),
                "ncbi_n": int((1 - y).sum()),
                "roc_auc": float(roc_auc_score(y, oof)),
                "average_precision": float(average_precision_score(y, oof)),
                "balanced_accuracy": float(balanced_accuracy_score(y, pred)),
                "mcc": float(matthews_corrcoef(y, pred)),
                "sensitivity_local": safe_div(tp, tp + fn),
                "specificity_ncbi": safe_div(tn, tn + fp),
            }
        )

    skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_SEED)
    run_scheme("stratified_random_5fold", skf.split(Xn, y))

    if mlst is not None and StratifiedGroupKFold is not None:
        # MLST can contain a mixture of numeric ST values and unresolved strings.
        # Normalize every entry explicitly to a pure string array BEFORE grouping.
        # Avoid np.unique(object), which sorts and can fail when mixed float/str
        # objects survive pandas conversion.
        groups = np.asarray(
            [
                "UNRESOLVED"
                if pd.isna(v) or str(v).strip() == "" or str(v).strip().lower() == "nan"
                else str(v).strip()
                for v in mlst.tolist()
            ],
            dtype=str,
        )
        if len(set(groups.tolist())) >= 5:
            try:
                sgkf = StratifiedGroupKFold(
                    n_splits=5,
                    shuffle=True,
                    random_state=RANDOM_SEED,
                )
                run_scheme("MLST_grouped_5fold", sgkf.split(Xn, y, groups=groups))
            except Exception as exc:
                rows.append(
                    {
                        "scheme": "MLST_grouped_5fold_SKIPPED",
                        "n": len(y),
                        "local_n": int(y.sum()),
                        "ncbi_n": int((1 - y).sum()),
                        "roc_auc": np.nan,
                        "average_precision": np.nan,
                        "balanced_accuracy": np.nan,
                        "mcc": np.nan,
                        "sensitivity_local": np.nan,
                        "specificity_ncbi": np.nan,
                        "note": str(exc),
                    }
                )

    return pd.DataFrame(rows)


