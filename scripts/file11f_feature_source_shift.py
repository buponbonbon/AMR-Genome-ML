def source_feature_associations(
    X: pd.DataFrame,
    source_local: np.ndarray,
    feature_names: list[str],
    resistance_coefficients: pd.DataFrame,
) -> pd.DataFrame:
    local = np.asarray(source_local, dtype=bool)
    ncbi = ~local

    coef_map = (
        resistance_coefficients.set_index("feature")["coefficient"].to_dict()
        if {"feature", "coefficient"}.issubset(resistance_coefficients.columns)
        else {}
    )

    rows = []
    arr = X[feature_names].to_numpy(dtype=np.uint8)

    for j, feature in enumerate(feature_names):
        present = arr[:, j].astype(bool)

        a = int(np.sum(present & local))
        b = int(np.sum((~present) & local))
        c = int(np.sum(present & ncbi))
        d = int(np.sum((~present) & ncbi))

        p_local = safe_div(a, a + b)
        p_ncbi = safe_div(c, c + d)
        delta = p_local - p_ncbi

        try:
            odds, pval = fisher_exact([[a, b], [c, d]], alternative="two-sided")
            odds = float(odds)
            pval = float(pval)
        except Exception:
            odds, pval = float("nan"), float("nan")

        coef = float(coef_map.get(feature, np.nan))
        rows.append(
            {
                "feature": feature,
                "local_present": a,
                "local_absent": b,
                "ncbi_present": c,
                "ncbi_absent": d,
                "local_prevalence": p_local,
                "ncbi_prevalence": p_ncbi,
                "local_minus_ncbi_prevalence": delta,
                "absolute_prevalence_shift": abs(delta),
                "source_odds_ratio_local_vs_ncbi": odds,
                "source_fisher_p": pval,
                "resistance_model_coefficient": coef,
                "abs_resistance_model_coefficient": abs(coef) if np.isfinite(coef) else np.nan,
            }
        )

    out = pd.DataFrame(rows)
    out["source_fisher_q_BH"] = bh_fdr(out["source_fisher_p"].to_numpy())
    out["primary_source_marker"] = (
        (out["source_fisher_q_BH"] <= SOURCE_MARKER_Q)
        & (out["absolute_prevalence_shift"] >= SOURCE_MARKER_ABS_SHIFT)
    )
    out["coefficient_weighted_abs_source_shift"] = (
        out["abs_resistance_model_coefficient"]
        * out["absolute_prevalence_shift"]
    )

    return out.sort_values(
        ["primary_source_marker", "absolute_prevalence_shift", "source_fisher_q_BH"],
        ascending=[False, False, True],
        na_position="last",
    )


