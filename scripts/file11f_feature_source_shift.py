def map_binary_series(s: pd.Series) -> pd.Series | None:
    raw = s.copy()

    numeric = pd.to_numeric(raw, errors="coerce")
    nonmissing = numeric.dropna()
    if len(nonmissing) and set(nonmissing.unique()).issubset({0, 1}):
        return numeric.astype("Float64")

    text = raw.astype(str).str.strip().str.upper()
    mapper = {
        "R": 1,
        "RESISTANT": 1,
        "RESISTANCE": 1,
        "1": 1,
        "1.0": 1,
        "S": 0,
        "SUSCEPTIBLE": 0,
        "SUSCEPTIBILITY": 0,
        "0": 0,
        "0.0": 0,
    }
    mapped = text.map(mapper)
    original_not_missing = ~raw.isna()
    if original_not_missing.sum() and mapped[original_not_missing].notna().all():
        return mapped.astype("Float64")

    return None


def likely_id_columns(columns: list[str]) -> list[str]:
    out = []
    for c in columns:
        lc = c.strip().lower()
        score = 0
        for i, hint in enumerate(ID_HINTS):
            if lc == hint:
                score += 100 - i
            elif hint in lc:
                score += 10
        if score:
            out.append((score, c))
    return [c for _, c in sorted(out, reverse=True)]


def likely_label_columns(columns: list[str]) -> list[str]:
    out = []
    for c in columns:
        lc = c.strip().lower()
        score = 0
        for i, hint in enumerate(LABEL_HINTS):
            if lc == hint:
                score += 100 - i
            elif hint in lc:
                score += 10
        if score:
            out.append((score, c))
    return [c for _, c in sorted(out, reverse=True)]


def find_mlst_column(columns: list[str]) -> str | None:
    exact_priority = ["MLST", "mlst", "sequence_type", "Sequence Type", "ST", "st"]
    for c in exact_priority:
        if c in columns:
            return c

    for c in columns:
        lc = c.strip().lower()
        if "mlst" in lc or "sequence_type" in lc or "sequence type" in lc:
            return c
    return None


def read_table(path: Path) -> pd.DataFrame:
    suffix = path.suffix.lower()
    if suffix == ".csv":
        return pd.read_csv(path, low_memory=False)
    if suffix in {".tsv", ".txt"}:
        return pd.read_csv(path, sep="\t", low_memory=False)
    if suffix == ".parquet":
        return pd.read_parquet(path)
    raise ValueError(f"Unsupported table format: {path}")


def candidate_label_files(root: Path) -> list[Path]:
    preferred = []
    patterns = [
        "**/*file07*.csv",
        "**/*fold*.csv",
        "**/*split*.csv",
        "**/*cohort*.csv",
        "**/*phenotype*.csv",
        "**/*meropenem*.csv",
        "**/*file07*.tsv",
        "**/*fold*.tsv",
        "**/*split*.tsv",
        "**/*cohort*.tsv",
        "**/*phenotype*.tsv",
        "**/*file07*.parquet",
        "**/*fold*.parquet",
        "**/*cohort*.parquet",
    ]
    seen = set()
    for pattern in patterns:
        for p in root.glob(pattern):
            if not p.is_file():
                continue
            rp = p.resolve()
            if rp in seen:
                continue
            seen.add(rp)
            # Do not inspect very large feature matrices or FILE11 external outputs.
            try:
                size = p.stat().st_size
            except OSError:
                continue
            if size > 120 * 1024 * 1024:
                continue
            lname = p.name.lower()
            if any(x in lname for x in ("unitig", "pangenome", "known_amr_final", "file11c_external")):
                continue
            preferred.append(p)

    def rank(p: Path) -> tuple:
        name = p.name.lower()
        path = str(p).lower()
        return (
            0 if "file07" in name else 1,
            0 if "common" in name or "cohort" in name else 1,
            0 if "fold" in name or "split" in name else 1,
            0 if "validation" in path else 1,
            len(str(p)),
        )

    return sorted(preferred, key=rank)


def evaluate_label_candidate(
    path: Path,
    x_ids: set[str],
) -> tuple[pd.DataFrame, str, str, str | None] | None:
    try:
        df = read_table(path)
    except Exception:
        return None
    if len(df) < EXPECTED_DEV_N:
        return None

    id_cols = likely_id_columns(list(df.columns))
    label_cols = likely_label_columns(list(df.columns))

    # If label hints miss, inspect low-cardinality columns.
    if not label_cols:
        for c in df.columns:
            if df[c].nunique(dropna=True) <= 5:
                label_cols.append(c)

    for id_col in id_cols[:5]:
        ids = df[id_col].map(norm_id)
        overlap = ids.isin(x_ids)
        if int(overlap.sum()) < EXPECTED_DEV_N:
            continue

        for label_col in label_cols[:15]:
            if label_col == id_col:
                continue
            mapped = map_binary_series(df[label_col])
            if mapped is None:
                continue

            tmp = pd.DataFrame(
                {
                    "genome_id": ids,
                    "label_binary": mapped,
                }
            )
            mlst_col = find_mlst_column(list(df.columns))
            if mlst_col is not None:
                tmp["MLST"] = df[mlst_col]

            tmp = tmp[tmp["genome_id"].isin(x_ids)].copy()
            tmp = tmp[tmp["label_binary"].notna()].copy()
            if tmp.empty:
                continue

            # Require duplicate IDs to have consistent labels.
            inconsistent = (
                tmp.groupby("genome_id")["label_binary"].nunique(dropna=True) > 1
            )
            if inconsistent.any():
                continue

            tmp = tmp.drop_duplicates("genome_id", keep="first")
            if len(tmp) != EXPECTED_DEV_N:
                continue

            tmp["label_binary"] = tmp["label_binary"].astype(int)
            r = int(tmp["label_binary"].sum())
            s = int(len(tmp) - r)
            if r == EXPECTED_DEV_R and s == EXPECTED_DEV_S:
                return tmp, id_col, label_col, mlst_col

    return None



def load_canonical_file07_common_cohort(
    root: Path,
    x_ids: set[str],
) -> tuple[pd.DataFrame, dict[str, Any]] | None:
    """
    Prefer the locked File07 cohort schema when available:
      Genome ID, Phenotype, y, MLST

    This avoids heuristic label discovery and uses the exact development cohort
    that generated FILE08/FILE09. The binary outcome is taken from `y`; the
    Phenotype column is cross-checked against y.
    """
    path = root / "data/processed/file07_common_cohort.csv"
    if not path.is_file():
        return None

    # Force Genome ID to string to avoid numeric coercion changing identifiers.
    df = pd.read_csv(path, dtype={"Genome ID": str}, low_memory=False)

    required = {"Genome ID", "Phenotype", "y", "MLST"}
    if not required.issubset(df.columns):
        return None

    if len(df) != EXPECTED_DEV_N:
        raise RuntimeError(
            f"Canonical File07 common cohort has n={len(df)}, "
            f"expected {EXPECTED_DEV_N}."
        )

    ids = df["Genome ID"].map(norm_id)
    if ids.duplicated().any():
        dup = ids[ids.duplicated(keep=False)].unique()[:20].tolist()
        raise RuntimeError(
            f"Canonical File07 common cohort has duplicate Genome IDs: {dup}"
        )

    y = pd.to_numeric(df["y"], errors="raise").astype(int)
    if not set(y.unique()).issubset({0, 1}):
        raise RuntimeError("Canonical File07 `y` is not binary 0/1.")

    pheno = df["Phenotype"].astype(str).str.strip().str.upper()
    pheno_y = pheno.map({"S": 0, "R": 1})
    if pheno_y.isna().any():
        bad = sorted(pheno[pheno_y.isna()].unique())[:20]
        raise RuntimeError(
            f"Canonical File07 Phenotype has unexpected values: {bad}"
        )
    if not np.array_equal(pheno_y.to_numpy(dtype=int), y.to_numpy(dtype=int)):
        raise RuntimeError("Canonical File07 Phenotype and y columns disagree.")

    r = int(y.sum())
    s = int(len(y) - r)
    if r != EXPECTED_DEV_R or s != EXPECTED_DEV_S:
        raise RuntimeError(
            f"Canonical File07 outcome signature mismatch: n={len(y)}, R={r}, S={s}"
        )

    overlap_mask = ids.isin(x_ids)
    overlap_n = int(overlap_mask.sum())
    missing_ids = sorted(set(ids) - x_ids)
    if overlap_n != EXPECTED_DEV_N:
        raise RuntimeError(
            "Canonical File07 development IDs are not fully represented in the "
            f"raw known-AMR matrix: overlap={overlap_n}/{EXPECTED_DEV_N}, "
            f"missing={len(missing_ids)}, examples={missing_ids[:20]}"
        )

    labels = pd.DataFrame(
        {
            "genome_id": ids,
            "label_binary": y,
            "MLST": df["MLST"],
        }
    )

    meta = {
        "selected_path": str(path),
        "id_column": "Genome ID",
        "label_column": "y",
        "phenotype_crosscheck_column": "Phenotype",
        "mlst_column": "MLST",
        "selection_mode": "canonical_file07_common_cohort",
        "audit": [
            {
                "path": str(path),
                "matched_exact_development_signature": True,
                "n": len(df),
                "R": r,
                "S": s,
                "ID_overlap_with_known_AMR": overlap_n,
            }
        ],
    }
    return labels, meta


def discover_development_labels(
    root: Path,
    x_ids: set[str],
    explicit: Path | None,
) -> tuple[pd.DataFrame, dict[str, Any]]:
    candidates = [explicit] if explicit is not None else candidate_label_files(root)

    audit_rows = []
    for i, path in enumerate(candidates, start=1):
        if path is None or not path.is_file():
            continue
        log(f"[PROGRESS] label discovery {i}/{len(candidates)} | {path}")
        result = evaluate_label_candidate(path, x_ids)
        audit_rows.append(
            {
                "path": str(path),
                "matched_exact_development_signature": result is not None,
            }
        )
        if result is not None:
            labels, id_col, label_col, mlst_col = result
            meta = {
                "selected_path": str(path),
                "id_column": id_col,
                "label_column": label_col,
                "mlst_column": mlst_col,
                "audit": audit_rows,
            }
            return labels, meta

    msg = (
        "Could not automatically locate a development label table with exactly "
        f"n={EXPECTED_DEV_N}, R={EXPECTED_DEV_R}, S={EXPECTED_DEV_S}. "
        "Rerun with --development-labels /path/to/File07_or_phenotype_table.csv"
    )
    raise RuntimeError(msg)


