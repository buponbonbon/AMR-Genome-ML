def positive_probability(model: LogisticRegression, X: np.ndarray) -> np.ndarray:
    classes = list(model.classes_)
    if 1 not in classes:
        raise RuntimeError(f"Model classes do not include positive class 1: {classes}")
    j = classes.index(1)
    return model.predict_proba(X)[:, j]


def extract_frozen_estimator(artifact: Any) -> Any:
    if hasattr(artifact, "predict_proba"):
        return artifact
    if isinstance(artifact, dict):
        for key in ("model", "estimator", "classifier", "clf"):
            obj = artifact.get(key)
            if hasattr(obj, "predict_proba"):
                return obj
    return None


